// Packs the pets in art/starter-pets (one folder each: pet.json and a PNG strip per
// loop, as in the pets folder) into main, which puts each in your pets folder the
// first time Gloom starts without it (main/pets.ts):
//   npm run starter-pets
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const art = join(root, 'art/starter-pets')
const pets = {}
for (const id of readdirSync(art).sort()) {
  pets[id] = {}
  for (const file of readdirSync(join(art, id)).sort()) pets[id][file] = readFileSync(join(art, id, file)).toString('base64')
}
writeFileSync(
  join(root, 'src/main/starter-pets.ts'),
  `// Generated by art/build-starter-pets.mjs from art/starter-pets: run \`npm run starter-pets\`, don't edit.
/** Pets that come with Gloom: each pet's files (pet.json and its loops' strips), base64. */
export const STARTER_PETS: Record<string, Record<string, string>> = ${JSON.stringify(pets, null, 2)}
`
)
console.log(`Starter pets: ${Object.keys(pets).join(', ')}`)
