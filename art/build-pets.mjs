// Builds the pets (art/pets.px.js) with pxl, the pixel-art DSL
// (github.com/crsolver/claude-pxl), and copies each pet's two loops into the
// renderer with a manifest of their frame sizes and timings:
//   npm run pets
// pxl lives in the Claude Code skill folder (~/.claude/skills/pxl-pixel-art), or
// where PXL points. It needs Node >= 22.18; on an older Node it runs under Node 24
// through npx.
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const art = join(root, 'art')
const target = join(root, 'src/renderer/src/features/pet/sprites')
const pxl = process.env.PXL ?? join(homedir(), '.claude/skills/pxl-pixel-art/bin/pxl.js')
const PETS = ['blob', 'sprout', 'ghost', 'ember', 'cat', 'frog', 'bot', 'owl']
const LOOPS = ['idle', 'busy', 'walk', 'fall', 'happy', 'jump']
/** Played once, then the pet goes back to what it was doing. */
const ONCE = new Set(['jump'])

const [major, minor] = process.versions.node.split('.').map(Number)
const modern = major > 22 || (major === 22 && minor >= 18)
const shell = process.platform === 'win32'
const only = PETS.flatMap((p) => LOOPS.map((l) => `${p}_${l}`)).join(',')
const args = [pxl, 'build', join(art, 'pets.px.js'), '--only', only]
if (modern) execFileSync(process.execPath, args, { stdio: 'inherit' })
else execFileSync('npx', ['-y', 'node@24', ...args], { stdio: 'inherit', shell })

rmSync(target, { recursive: true, force: true })
mkdirSync(target, { recursive: true })
const imports = []
const entries = []
for (const pet of PETS) {
  const loops = []
  for (const loop of LOOPS) {
    const name = `${pet}_${loop}`
    copyFileSync(join(art, 'out/anims', `${name}.png`), join(target, `${name}.png`))
    const sheet = JSON.parse(readFileSync(join(art, 'out/anims', `${name}.json`), 'utf8'))
    const frames = Object.values(sheet.frames)
    const { w, h } = frames[0].frame
    imports.push(`import ${name} from './${name}.png'`)
    loops.push(`${loop}: { src: ${name}, w: ${w}, h: ${h}, durations: [${frames.map((f) => f.duration).join(', ')}]${ONCE.has(loop) ? ', once: true' : ''} }`)
  }
  entries.push(`  ${pet}: { ${loops.join(', ')} }`)
}
writeFileSync(
  join(target, 'index.ts'),
  `// Generated by art/build-pets.mjs from art/pets.px.js: run \`npm run pets\`, don't edit.
import type { PetKind } from '@shared/live'
${imports.join('\n')}

/** One loop: a horizontal strip of w × h frames, each shown for its duration (ms); \`once\` plays it a single time. */
export interface PetLoop {
  src: string
  w: number
  h: number
  durations: readonly number[]
  once?: boolean
}

/** idle: resting; busy: working; walk: carried sideways (facing right); fall: held up; happy: under the pointer; jump: clicked. */
export type PetLoopName = ${LOOPS.map((l) => `'${l}'`).join(' | ')}

export const PET_SPRITES: Record<PetKind, Record<PetLoopName, PetLoop>> = {
${entries.join(',\n')}
}
`
)
console.log(`Pets: ${PETS.length} × ${LOOPS.length} loops in ${target}`)
